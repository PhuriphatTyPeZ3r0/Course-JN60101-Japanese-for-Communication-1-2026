// Minimal 16x16 ICO generator
const fs = require('fs');

// ICO Header: 6 bytes (0,0, 1,0, 1,0)
const header = Buffer.from([0, 0, 1, 0, 1, 0]);

// Minimal 1x1 transparent/red PNG:
const png = Buffer.from([
  0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a,
  0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52,
  0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x10,
  0x08, 0x06, 0x00, 0x00, 0x00, 0x1f, 0xf3, 0xff,
  0x61, 0x00, 0x00, 0x00, 0x19, 0x49, 0x44, 0x41,
  0x54, 0x78, 0x9c, 0x63, 0xfc, 0xcf, 0x80, 0x01,
  0x30, 0x24, 0x00, 0x04, 0x80, 0x00, 0x01, 0x1d,
  0x0b, 0x08, 0x02, 0x00, 0x00, 0x00, 0x00, 0x49,
  0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82
]);

// Directory Entry: 16 bytes
// width=16, height=16, colorCount=0, reserved=0, planes=1, bpp=32, size=png.length, offset=22
const dirEntry = Buffer.alloc(16);
dirEntry.writeUInt8(16, 0); // width
dirEntry.writeUInt8(16, 1); // height
dirEntry.writeUInt8(0, 2);  // colorCount
dirEntry.writeUInt8(0, 3);  // reserved
dirEntry.writeUInt16LE(1, 4); // color planes
dirEntry.writeUInt16LE(32, 6); // bits per pixel
dirEntry.writeUInt32LE(png.length, 8); // image size
dirEntry.writeUInt32LE(22, 12); // image offset

const icoBuffer = Buffer.concat([header, dirEntry, png]);
fs.writeFileSync('public/favicon.ico', icoBuffer);
console.log('public/favicon.ico created successfully, size:', icoBuffer.length);
